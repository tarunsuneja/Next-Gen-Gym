import { chromium } from "@playwright/test";
import { mkdir, readFile, writeFile } from "node:fs/promises";

const LOGO = "public/ngf-logo.jpg";
const BG = "#000000";

const data = await readFile(LOGO);
const src = `data:image/jpeg;base64,${data.toString("base64")}`;

const targets = [
  { file: "favicon-32.png", size: 32, scale: 1 },
  { file: "favicon-48.png", size: 48, scale: 1 },
  { file: "icon-192.png", size: 192, scale: 1 },
  { file: "icon-512.png", size: 512, scale: 1 },
  { file: "icon-maskable-512.png", size: 512, scale: 0.72 },
  { file: "apple-touch-icon.png", size: 180, scale: 1 },
];

await mkdir("public/icons", { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.GYMDESK_BROWSER_PATH || undefined });
const page = await browser.newPage({ viewport: { width: 512, height: 512 } });
for (const t of targets) {
  await page.setViewportSize({ width: t.size, height: t.size });
  const box = Math.round(t.size * t.scale);
  await page.setContent(
    `<!doctype html><html><head><style>html,body{margin:0;padding:0;background:${BG};width:${t.size}px;height:${t.size}px;overflow:hidden;display:flex;align-items:center;justify-content:center}</style></head><body><img src="${src}" width="${box}" height="${box}" style="display:block;width:${box}px;height:${box}px;object-fit:contain"/></body></html>`,
    { waitUntil: "load" },
  );
  await page.screenshot({ path: `public/icons/${t.file}` });
  console.log("wrote", `public/icons/${t.file}`, t.size);
}
await browser.close();

await writeFile(
  "public/icons/README.txt",
  "Generated by scripts/generate-icons.mjs from public/ngf-logo.jpg. Do not hand-edit.\n",
);
console.log("done");
